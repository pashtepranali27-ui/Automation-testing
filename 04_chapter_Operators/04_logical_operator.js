//&&--AND and ||--> OR operator
let a = true;
let b = false;

console.log(a && b); // false, bcz here a is true and b is false, so it will return false.
console.log(a || b); // true, bcz here a is true and b is false, so it will return true.
console.log(!a); // false, bcz here a is true, so it will return false. 
