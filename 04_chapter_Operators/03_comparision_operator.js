// == ,===
// = loose comparison operator(sikh,hindu)
// === strict comparison operator (sikh vs hindu,language, caste, religion, et)
 // eg pizza vs pizza == pizza -> 
 //pizza dominos === pizza pizzahut

  console.log("5" == 5); // true loose comparison operator, bcz here "5" is string and 5 is number, so it will convert string to number and then compare, so it will return true.
  console.log("5" === 5); // false,bcz here "5" is string and 5 is number, so they are not same data type, so it will return false.
  
  // != , !==
  console.log("5" != 5); // false, bcz here "5" is string and 5 is number, so it will convert string to number and then compare, so it will return false.
  console.log("5" !== 5); // true, bcz here "5" is string and 5 is number, so they are not same data type, so it will return true.  

  console.log(5 === 5);// true, bcz here 5 is number and 5 is number, so they are same data type and same value, so it will return true.
